const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.DEMO_BROWSER_CHANNEL ? { channel: process.env.DEMO_BROWSER_CHANNEL } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve('index.html')).href);
    const enter = () => page.evaluate(() => { setScreen('workspace'); applyRole('requester'); setView('department'); setDeptTab('request'); });
    await enter();
    await page.evaluate(() => openRequestItemPicker());
    await page.locator('#requestItemPickerQuery').fill('IPC');
    await page.locator('[data-request-picker-source-tab="new"]').click();
    const grouped = await page.evaluate(() => materialEntryRow().duplicateCandidates);
    assert.equal(new Set(grouped.map(r => JSON.stringify([r.name, r.spec]))).size, grouped.length);
    assert.ok(grouped.some(r => r.origins.length > 1), 'Repeated sources are retained in one suggestion');
    await page.locator('#materialEntryStandardNameCn').fill('State audit item');
    await page.locator('[data-action="enterNewItemDetails"]').click();
    await page.locator('#materialEntrySpec').fill('Capacity 250 ml');
    await page.reload(); await enter();
    await page.evaluate(() => openRequestItemPicker());
    await page.locator('[data-request-picker-source-tab="new"]').click();
    assert.equal(await page.locator('#materialEntryStandardNameCn').inputValue(), 'State audit item');
    assert.equal(await page.locator('#materialEntrySpec').inputValue(), 'Capacity 250 ml', 'Unfinished new item survives reload');
    await page.locator('[data-action="returnToItemMatches"]').click();
    await page.locator('[data-action="backToItemSearch"]').click();
    assert.equal(await page.locator('#requestItemPickerQuery').inputValue(), 'State audit item');
    await page.locator('[data-request-picker-source-tab="new"]').click();
    await page.locator('[data-action="enterNewItemDetails"]').click();
    assert.equal(await page.locator('#materialEntrySpec').inputValue(), 'Capacity 250 ml');
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.action), 'openRequestItemPicker');
    await page.evaluate(() => openRequestItemPicker());
    await page.locator('[data-request-picker-source-tab="new"]').click();
    assert.equal(await page.locator('#materialEntrySpec').inputValue(), 'Capacity 250 ml');
    for (const n of [1, 2, 3]) await page.locator(`#materialEntryLevel${n}`).selectOption({ index: 1 });
    await page.locator('#materialEntryUom').selectOption('PCS');
    await page.locator('#materialEntryUseCase').fill('Local draft recovery');
    await page.locator('#materialEntryForm button[type="submit"]').click();
    await page.evaluate(() => { const row = requests.find(r => r.name === 'State audit item'); updateRequestWorksheetQty(row.id, 'p10', requestWorksheetColumns()[0], 4); saveRequesterDraft(); });
    await page.reload(); await enter();
    const restored = await page.evaluate(() => requests.find(r => r.name === 'State audit item'));
    assert.ok(restored);
    assert.equal(restored.spec, 'Capacity 250 ml'); assert.equal(restored.uom, 'PCS'); assert.equal(restored.p10, 4);
    assert.equal(restored.itemMasterRequestStatus, 'Pending Material Review');
    const otherAccount = await page.evaluate(() => {
      const original = currentRequesterPersonaId;
      const key = requesterLocalDraftKey();
      const other = requesterPersonas().find(p => p.id !== original && p.employeeId);
      if (!other) throw new Error('Missing alternate requester fixture');
      currentRequesterPersonaId = other.id;
      const result = { differentKey: requesterLocalDraftKey() !== key, contains: readRequesterLocalDrafts().some(r => r.name === 'State audit item') };
      currentRequesterPersonaId = original;
      return result;
    });
    assert.equal(otherAccount.differentKey, true);
    assert.equal(otherAccount.contains, false);
    await page.evaluate(() => { const row = requests.find(r => r.name === 'State audit item'); row.requiredDeliveryDate = '2026-10-15'; submitRequests(); });
    assert.equal(await page.evaluate(() => requests.find(r => r.name === 'State audit item').status), 'Submitted');
    await page.reload(); await enter();
    const submitted = await page.evaluate(() => requests.filter(r => r.name === 'State audit item'));
    assert.equal(submitted.length, 1, 'Submitted row replaces saved draft');
    assert.equal(submitted[0].status, 'Submitted');
    await page.evaluate(() => openRequestItemPicker());
    await page.locator('[data-add-worksheet-source]').first().click();
    const savedId = await page.evaluate(() => { const id = requests[0].id; saveRequesterDraft(); return id; });
    await page.evaluate(id => removeRequest(id), savedId);
    await page.reload(); await enter();
    assert.equal(await page.evaluate(id => requests.some(r => r.id === id), savedId), false, 'Removed draft must not return');
    await page.evaluate(() => createNewItemSuggestion({ query: 'Discard me' }));
    await page.locator('[data-action="discardMaterialDraft"]').click();
    assert.equal(await page.evaluate(() => newItemSuggestions.some(r => r.name === 'Discard me')), false);
    await page.reload(); await enter();
    await page.evaluate(() => createNewItemSuggestion({ query: 'Fresh after discard' }));
    assert.equal(await page.locator('#materialEntryStandardNameCn').inputValue(), 'Fresh after discard');
    const storageFailure = await page.evaluate(() => {
      const original = Storage.prototype.setItem;
      Storage.prototype.setItem = () => { throw new Error('quota'); };
      const result = persistRequesterLocalDrafts([]);
      Storage.prototype.setItem = original;
      return result;
    });
    assert.equal(storageFailure, false, 'Storage errors must be reported as failure');
    assert.deepEqual(errors, []);
    console.log('PASS: grouped suggestions, retained draft and search, Escape focus, reload recovery, submission without duplicates, permanent draft removal, explicit discard, storage failure.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
