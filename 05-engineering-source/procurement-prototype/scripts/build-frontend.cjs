const path = require('node:path');
const fs = require('node:fs');
const esbuild = require('esbuild');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');

async function buildFrontend({ check = false } = {}) {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['src/bootstrap/entry.js'],
    outfile: 'dist/app.bundle.js',
    bundle: true,
    format: 'iife',
    globalName: 'ProcurementRuntime',
    platform: 'browser',
    target: ['es2022'],
    charset: 'utf8',
    keepNames: true,
    minify: false,
    sourcemap: 'linked',
    sourcesContent: true,
    metafile: true,
    write: false,
    banner: { js: '// GENERATED by npm run build. Edit src/, never this file.' },
  });
  for (const output of result.outputFiles) {
    if (check) {
      if (!fs.existsSync(output.path) || !fs.readFileSync(output.path).equals(Buffer.from(output.contents))) {
        throw new Error(`Stale frontend artifact: ${path.relative(root, output.path)}. Run npm run build.`);
      }
    } else {
      fs.mkdirSync(path.dirname(output.path), { recursive: true });
      fs.writeFileSync(output.path, output.contents);
    }
  }
  const hashes = {};
  for (const file of [...Object.keys(result.metafile.inputs), 'scripts/build-frontend.cjs']) {
    hashes[file] = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
  }
  for (const output of result.outputFiles) {
    hashes[path.relative(root, output.path).split(path.sep).join('/')] = crypto.createHash('sha256').update(output.contents).digest('hex');
  }
  const manifest = JSON.stringify({ schemaVersion: 1, files: hashes }, null, 2) + '\n';
  const manifestPath = path.join(root, 'dist/build-manifest.json');
  if (check) {
    if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath,'utf8') !== manifest) throw new Error('Stale build manifest. Run npm run build.');
  } else fs.writeFileSync(manifestPath, manifest);
  return result.metafile;
}

if (require.main === module) {
  buildFrontend({ check: process.argv.includes('--check') })
    .then(meta => console.log(`Frontend ${process.argv.includes('--check') ? 'verified' : 'built'}: ${Object.keys(meta.inputs).length} source modules.`))
    .catch(error => { console.error(error.message); process.exitCode = 1; });
}
module.exports = { buildFrontend };
